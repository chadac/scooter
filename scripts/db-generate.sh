#!/usr/bin/env bash
# db-generate.sh — regenerate everything derived from the schema spec.
#
# Two sources, in order: the `scooter.db` module option (the topology: which
# databases exist, which tables are in each, who writes and who reads) renders
# lib/sql/owners.toml and lib/sql/atlas.hcl (core databases) plus each contrib
# database's contrib/<name>/sql/{owners.toml,atlas.hcl}, and then lib/sql/<db>/schema.sql
# renders lib/ts/scooter-schema/src/<db>.ts (Drizzle, via drizzle-kit pull) and
# lib/py/scooter-schema/src/scooter_schema/<db>.py (SQLAlchemy, via sqlacodegen).
# owners.toml's top-level `[<database>]` sections are the database list that step
# 2 iterates. Each schema is loaded into an embedded pglite, so no real Postgres
# is touched and concurrent runs never interfere.
#
# Regenerate whenever a schema.sql changes; `just db-generate-check` fails CI if
# the committed output drifts. Needs node + npx (drizzle-kit, @electric-sql/pglite
# from the workspace install) and uv; run from the repo root.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

# drizzle-kit and pglite come from the workspace install.
npm install

# --- step 1: render the spec artifacts from the module system ----------------
# Built rather than `nix eval`ed, so both files come from one derivation and
# cannot disagree.
echo "rendering the spec artifacts from scooter.db ..."
spec="$(nix build --no-link --print-out-paths "$ROOT#db-spec")"
install -m 644 "$spec/owners.toml"    lib/sql/owners.toml
install -m 644 "$spec/atlas.hcl"      lib/sql/atlas.hcl
# Each contrib database's owners.toml + atlas.hcl, into its own contrib/<name>/sql.
if [ -d "$spec/contrib" ]; then
  (cd "$spec" && find contrib -type f) | while read -r f; do install -D -m 644 "$spec/$f" "$f"; done
fi

# Bindings are core-only: a contrib database (its own contrib/<name>/sql) is private to
# its contrib, which keeps its own row model, so core never learns it exists.
CORE_ENVS="$(scripts/db-sql-dir.sh --core)"
TS_OUT="lib/ts/scooter-schema/src"
PY_OUT="lib/py/scooter-schema/src/scooter_schema"
SQLACODEGEN_VERSION="4.0.4"
# sqlacodegen does not pin SQLAlchemy, whose version decides the generated
# annotations, so pin it too and bump deliberately (raise, regenerate, review the
# diff).
SQLALCHEMY_VERSION="2.0.54"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

ts_header() { printf '// @generated by `just db-generate` from lib/sql/%s/schema.sql — do not edit.\n// Regenerate after a schema change; CI fails on drift (just db-generate-check).\n\n' "$1"; }
py_header() { printf '# @generated by `just db-generate` from lib/sql/%s/schema.sql — do not edit.\n# Regenerate after a schema change; CI fails on drift (just db-generate-check).\n\n' "$1"; }

for env in $CORE_ENVS; do
  schema="$ROOT/lib/sql/$env/schema.sql"
  echo "generating $env ..."

  # --- TypeScript (Drizzle) --------------------------------------------------
  # Load schema.sql into a throwaway pglite data dir, then drizzle-kit pull.
  datadir="$work/pg-$env"
  node -e "import('@electric-sql/pglite').then(async ({ PGlite }) => {
    const db = new PGlite('$datadir');
    await db.exec(require('fs').readFileSync('$schema', 'utf8'));
    await db.close();
  })"
  # Plain object (no `defineConfig` import) so the config resolves no modules from
  # its temp-dir location.
  cat > "$work/drizzle-$env.config.ts" <<CFG
export default {
  dialect: 'postgresql',
  driver: 'pglite',
  dbCredentials: { url: '$datadir' },
  schema: './unused.ts',
  out: '$work/dz-$env',
};
CFG
  npx --no-install drizzle-kit pull --config="$work/drizzle-$env.config.ts" >/dev/null
  { ts_header "$env"; cat "$work/dz-$env/schema.ts"; } > "$TS_OUT/$env.ts"

  # --- Python (SQLAlchemy) ---------------------------------------------------
  # Expose the same schema from pglite on a loopback socket; sqlacodegen introspects it.
  port=$(( (RANDOM % 20000) + 20000 ))
  node -e "
    const { PGlite } = require('@electric-sql/pglite');
    const { PGLiteSocketServer } = require('@electric-sql/pglite-socket');
    (async () => {
      const db = new PGlite();
      await db.exec(require('fs').readFileSync('$schema', 'utf8'));
      const server = new PGLiteSocketServer({ db, port: $port, host: '127.0.0.1' });
      await server.start();
      process.stdout.write('READY');
    })();
  " > "$work/sock-$env.log" 2>"$work/sock-$env.err" &
  sockpid=$!
  for _ in $(seq 1 60); do grep -q READY "$work/sock-$env.log" 2>/dev/null && break; sleep 0.25; done
  uv run --quiet --with "sqlacodegen==$SQLACODEGEN_VERSION" \
    --with "sqlalchemy==$SQLALCHEMY_VERSION" --with psycopg2-binary \
    sqlacodegen "postgresql+psycopg2://postgres@127.0.0.1:$port/postgres" > "$work/models-$env.py"
  kill "$sockpid" 2>/dev/null || true
  wait "$sockpid" 2>/dev/null || true
  { py_header "$env"; cat "$work/models-$env.py"; } > "$PY_OUT/$env.py"
done

echo "generated: $TS_OUT/{$(echo "$CORE_ENVS" | tr ' ' ,)}.ts and $PY_OUT/{$(echo "$CORE_ENVS" | tr ' ' ,)}.py"
